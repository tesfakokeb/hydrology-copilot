export type StatusKind = 'normal' | 'watch' | 'warning' | 'critical' | 'unknown' | 'info' | 'success';

const STATUS_STYLES: Record<StatusKind, string> = {
  normal: 'border-emerald-200 bg-emerald-50 text-emerald-800',
  success: 'border-emerald-200 bg-emerald-50 text-emerald-800',
  watch: 'border-amber-200 bg-amber-50 text-amber-800',
  warning: 'border-orange-200 bg-orange-50 text-orange-800',
  critical: 'border-red-200 bg-red-50 text-red-800',
  unknown: 'border-ink-200 bg-ink-50 text-ink-600',
  info: 'border-hydro-200 bg-hydro-50 text-hydro-800',
};

const STATUS_DOT: Record<StatusKind, string> = {
  normal: 'bg-emerald-500',
  success: 'bg-emerald-500',
  watch: 'bg-amber-500',
  warning: 'bg-orange-500',
  critical: 'bg-red-500',
  unknown: 'bg-ink-400',
  info: 'bg-hydro-500',
};

export function StatusPill({ status, children, dot = true }: { status: StatusKind; children: ReactNode; dot?: boolean }) {
  return (
    <span className={`chip ${STATUS_STYLES[status]}`}>
      {dot && <span className={`h-1.5 w-1.5 rounded-full ${STATUS_DOT[status]}`} aria-hidden />}
      {children}
    </span>
  );
}

export function SyntheticBadge({ compact = false }: { compact?: boolean }) {
  return (
    <span
      className="chip border-violet-200 bg-violet-50 text-violet-800"
      title="Every value shown derives from a synthetic demonstration dataset generated by a conceptual rainfall-runoff model. No value is an observation."
    >
      <span className="h-1.5 w-1.5 rounded-full bg-violet-500" aria-hidden />
      {compact ? 'Synthetic' : 'Synthetic demonstration data'}
    </span>
  );
}

