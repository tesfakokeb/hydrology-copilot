export function Skeleton({ className = 'h-4 w-full' }: { className?: string }) {
  return <div className={`skeleton ${className}`} aria-hidden />;
}

export function LoadingPanel({ label = 'Computing…', lines = 4 }: { label?: string; lines?: number }) {
  return (
    <div className="space-y-3 p-4" role="status" aria-live="polite">
      <div className="flex items-center gap-2 text-xs text-ink-500">
        <Spinner />
        {label}
      </div>
      {Array.from({ length: lines }).map((_, i) => (
        <Skeleton key={i} className={`h-3 ${i % 3 === 0 ? 'w-5/6' : i % 3 === 1 ? 'w-full' : 'w-2/3'}`} />
      ))}
    </div>
  );
}

export function Spinner({ className = 'h-3.5 w-3.5' }: { className?: string }) {
  return (
    <svg className={`${className} animate-spin text-hydro-600`} viewBox="0 0 24 24" fill="none" aria-hidden>
      <circle className="opacity-20" cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="3" />
      <path className="opacity-90" fill="currentColor" d="M4 12a8 8 0 018-8v3a5 5 0 00-5 5H4z" />
    </svg>
  );
}

export function EmptyState({ title, body, action }: { title: string; body?: string; action?: ReactNode }) {
  return (
    <div className="flex flex-col items-center justify-center gap-2 rounded-lg border border-dashed border-ink-200 bg-ink-50/60 px-6 py-10 text-center">
      <p className="text-sm font-medium text-ink-700">{title}</p>
      {body && <p className="max-w-md text-xs text-ink-500">{body}</p>}
      {action}
    </div>
  );
}

export function ErrorState({ error, retry }: { error: unknown; retry?: () => void }) {
  const message = error instanceof Error ? error.message : String(error);
  return (
    <div className="rounded-lg border border-red-200 bg-red-50 px-4 py-3">
      <p className="text-sm font-semibold text-red-900">This analysis could not be completed</p>
      <p className="mt-1 text-xs text-red-800">{message}</p>
      {retry && (
        <button type="button" className="btn btn-secondary mt-3" onClick={retry}>
          Try again
        </button>
      )}
    </div>
  );
}

export function InsufficientData({ message }: { message: string }) {
  return (
    <div className="rounded-lg border border-amber-200 bg-amber-50 px-4 py-3">
      <p className="text-sm font-semibold text-amber-900">Insufficient data</p>
      <p className="mt-1 text-xs text-amber-800">{message}</p>
    </div>
  );
}

export function WarningList({ warnings, title = 'Cautions' }: { warnings: string[]; title?: string }) {
  if (warnings.length === 0) return null;
  return (
    <div className="rounded-md border border-amber-200 bg-amber-50 px-3 py-2">
      <p className="text-2xs font-semibold uppercase tracking-wide text-amber-900">{title}</p>
      <ul className="mt-1 space-y-1">
        {warnings.map((w, i) => (
          <li key={i} className="text-xs leading-relaxed text-amber-900">
            {w}
          </li>
        ))}
      </ul>
    </div>
  );
}

