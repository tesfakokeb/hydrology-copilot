export function Metric({
  label,
  value,
  unit,
  hint,
  status,
}: {
  label: string;
  value: ReactNode;
  unit?: string;
  hint?: string;
  status?: StatusKind;
}) {
  return (
    <div className="rounded-md border border-ink-200 bg-white px-3 py-2">
      <p className="text-2xs font-medium uppercase tracking-wide text-ink-500">{label}</p>
      <p className="mt-0.5 flex items-baseline gap-1">
        <span className={`text-lg font-semibold tabular ${status === 'critical' ? 'text-red-700' : 'text-ink-900'}`}>{value}</span>
        {unit && <span className="text-xs text-ink-500">{unit}</span>}
      </p>
      {hint && <p className="mt-0.5 text-2xs leading-snug text-ink-500">{hint}</p>}
    </div>
  );
}

// ---------------------------------------------------------------------------
// Tabs
// ---------------------------------------------------------------------------

export function Tabs<T extends string>({
  tabs,
  active,
  onChange,
}: {
  tabs: { id: T; label: string; count?: number }[];
  active: T;
  onChange: (id: T) => void;
}) {
  return (
    <div className="flex flex-wrap gap-1 border-b border-ink-200" role="tablist">
      {tabs.map((t) => (
        <button
          key={t.id}
          role="tab"
          aria-selected={active === t.id}
          type="button"
          onClick={() => onChange(t.id)}
          className={`-mb-px border-b-2 px-3 py-2 text-xs font-medium transition-colors ${
            active === t.id ? 'border-hydro-600 text-hydro-800' : 'border-transparent text-ink-500 hover:text-ink-800'
          }`}
        >
          {t.label}
          {t.count !== undefined && <span className="ml-1.5 rounded bg-ink-100 px-1 text-2xs text-ink-600">{t.count}</span>}
        </button>
      ))}
    </div>
  );
}

// ---------------------------------------------------------------------------
// Toasts
// ---------------------------------------------------------------------------

export function Toasts() {
  const { toasts, dismissToast } = useApp();
  if (toasts.length === 0) return null;
  return (
    <div className="pointer-events-none fixed bottom-4 right-4 z-50 flex w-80 flex-col gap-2">
      {toasts.map((t) => (
        <div
          key={t.id}
          className={`pointer-events-auto animate-fade-in rounded-lg border px-3 py-2 shadow-panel ${STATUS_STYLES[
            t.kind === 'error' ? 'critical' : t.kind === 'success' ? 'normal' : t.kind === 'warning' ? 'warning' : 'info'
          ]}`}
          role="status"
        >
          <div className="flex items-start justify-between gap-2">
            <p className="text-xs font-semibold">{t.title}</p>
            <button type="button" className="text-xs opacity-60 hover:opacity-100" onClick={() => dismissToast(t.id)} aria-label="Dismiss">
              ✕
            </button>
          </div>
          {t.body && <p className="mt-1 text-2xs leading-relaxed">{t.body}</p>}
        </div>
      ))}
    </div>
  );
}

