/**
 * Potomac Demonstration Watershed — SYNTHETIC data.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * THIS IS NOT REAL DATA. Nothing in this module is an observation.
 *
 * The series are produced by a deterministic conceptual rainfall-runoff model
 * (stochastic precipitation generator → soil-moisture store → two linear
 * reservoirs) with a seasonal climate signal and a multi-year wet/dry
 * oscillation. The catchment is loosely styled on the Potomac River basin
 * above Point of Rocks so that magnitudes are plausible, but no value
 * corresponds to any gauge reading, and the geometry is a generated shape,
 * not a delineated watershed boundary.
 *
 * It exists so that every analytical capability of the platform can be
 * exercised immediately after installation without external credentials.
 * Every record it produces is flagged `is_synthetic` and every provenance
 * record built from it says so.
 * ────────────────────────────────────────────────────────────────────────────
 */

