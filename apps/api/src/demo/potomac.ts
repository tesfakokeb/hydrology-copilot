/** Generate a closed, jittered polygon around a centre. */
function blob(center: { lon: number; lat: number }, radiusDeg: number, seed: number, n = 48): [number, number][] {
  const r = rng(seed);
  const pts: [number, number][] = [];
  const wobble = Array.from({ length: 5 }, () => r() * 2 - 1);
  for (let i = 0; i < n; i++) {
    const a = (2 * Math.PI * i) / n;
    let rad = radiusDeg;
    wobble.forEach((w, k) => {
      rad *= 1 + 0.11 * w * Math.sin((k + 2) * a + k);
    });
    pts.push([
      Number((center.lon + rad * Math.cos(a) * 1.32).toFixed(5)),
      Number((center.lat + rad * Math.sin(a) * 0.78).toFixed(5)),
    ]);
  }
  pts.push(pts[0]);
  return pts;
}

